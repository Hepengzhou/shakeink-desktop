function createFocusPrompt(template: WizardTemplate, revision: FocusRevision): string {
  const categoryTitle = { theme: "主题", world: "世界观", character: "角色", plot: "剧情" }[template.cat]
  return [
    `【${categoryTitle}】${revision.title}`,
    "【输入与缺省】\n读取当前对话以及已选择的定位、主题、世界观、角色信息，作者明确设定优先。缺少决定性信息时最多提出三个针对性问题，同时提供标为“待作者确认”的可执行建议；将已有事实、推测和建议分开。不虚构作者资料或已确定的故事事实。",
    `【指导问题】\n${revision.questions.map((question, index) => `${index + 1}. ${question}`).join("\n")}`,
    `【输出】\n先简述已知设定与假设，再逐项回应指导问题并完成以下交付：${revision.deliverable}用清晰小节或表格组织，通常 600–1200 字，优先保证设定可用和任务完整。`,
    `【自检】\n${revision.checks}核对是否遵守作者设定、是否存在互相矛盾的建议、所有未定信息是否已标注。发现问题先修正再交付。`,
  ].join("\n\n")
}

const PLOT_CONTRACT_SECTIONS = ["【输入与缺省】", "【方法】", "【推进步骤】", "【输出】", "【自检】"] as const

/** Curate built-ins without changing their stable IDs or filtering metadata. */
export function curateTemplate(template: WizardTemplate): WizardTemplate {
  const focusRevision = FOCUS_REVISIONS[template.id]
  if (focusRevision) {
    return {
      ...template,
      title: focusRevision.title,
      summary: focusRevision.summary,
      prompt: createFocusPrompt(template, focusRevision),
    }
  }

  if (template.cat !== "plot") return template
  // Newly authored plot-library entries already carry the complete contract.
  if (PLOT_CONTRACT_SECTIONS.every(section => template.prompt.includes(section))) return template

  const revision = PLOT_REVISIONS[template.id]
  const originalQuestions = template.prompt.replace(/^【剧情】[^\n]*\n*/, "").trim()
  const plot = createPlotTemplate(revision ?? {
    id: template.id,
    title: template.title,
    summary: template.summary,
    method: "沿用下列作者引导问题确定本条剧情的目标、冲突和取舍。先区分已定设定与待定方案，再将每个问题的回答连成有动机、有后果的主线，不把问题里的可选方向一律写成既成事实。",
    steps: [originalQuestions],
    deliverable: `交付“${template.title}”的关键问题回应与因果主线表：逐项说明采用的方向、相应事件、受影响的人和选择代价；若原问题提供互斥结局，应选定一种暂定方案并保留作者调整入口。`,
  })

  return {
    ...plot,
    ...template,
    title: plot.title,
    summary: plot.summary,
    prompt: plot.prompt,
  }
}
